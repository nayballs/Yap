#!/usr/bin/env node
// The site's colours, from the app's own: reads the app's design tokens in
// ../desktop/src/app.css (the light `:root` block, its warm dark and the bar's dark
// scheme) and writes src/styles/tokens.css for the site, so a colour changed
// in the app changes here on the next build.
//
// The app's `--yap-*` names become `--t-*` (the site never spells the product's
// name, which is about to change); the bar's `--bar-*` keep theirs. The site
// follows the visitor's system theme, or the footer's switch:
//   :root                                            light
//   @media (prefers-color-scheme: dark) :root:not([data-theme='light'])   dark
//   :root[data-theme='dark']                         dark
//
// Run by `npm run dev` and `npm run build`; `npm run tokens` on its own.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const appCss = path.resolve(here, '../../desktop/src/app.css');
const out = path.resolve(here, '../src/styles/tokens.css');

const css = fs.readFileSync(appCss, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');

/** Every top-level `selector { body }` block (app.css has no nesting). */
function blocks(text) {
  const found = [];
  const re = /([^{}]+)\{([^{}]*)\}/g;
  let m;
  while ((m = re.exec(text))) found.push({ selector: m[1].trim().replace(/\s+/g, ' '), body: m[2] });
  return found;
}

/** The custom properties with one of `prefixes` in a block body, in order. */
function props(body, prefixes) {
  const list = [];
  const re = /(--[a-z0-9-]+)\s*:\s*([^;]+);/gi;
  let m;
  while ((m = re.exec(body))) {
    if (prefixes.some((p) => m[1].startsWith(p))) list.push([m[1], m[2].trim().replace(/\s+/g, ' ')]);
  }
  return list;
}

const rename = (s) => s.replace(/--yap-/g, '--t-');

const all = blocks(css);
const pick = (selector, prefixes) =>
  all.filter((b) => b.selector === selector).flatMap((b) => props(b.body, prefixes));

const light = pick(':root', ['--yap-', '--bar-']).filter(([name]) => !name.startsWith('--yap-reading') && name !== '--yap-font-reading');
const dark = [
  ...pick(":root[data-yap-theme='dark']", ['--yap-']),
  ...pick(":root[data-bar-theme='dark']", ['--bar-']),
];

if (light.length < 50 || dark.length < 30) {
  console.error(`tokens: found ${light.length} light and ${dark.length} dark tokens in ${appCss}; has app.css changed shape?`);
  process.exit(1);
}

const decl = (list, indent) => list.map(([n, v]) => `${indent}${rename(n)}: ${rename(v)};`).join('\n');

const text = `/* GENERATED by scripts/tokens.mjs from the app's desktop/src/app.css. Don't edit:
   change the app's tokens, then \`npm run tokens\` (dev and build run it too). */

:root {
  color-scheme: light;
${decl(light, '  ')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${decl(dark, '    ')}
  }
}

:root[data-theme='dark'] {
  color-scheme: dark;
${decl(dark, '  ')}
}

/* The dark scheme on part of a light page: the ink sheets (global.css
   .sheet-ink), so the app's own UI drawn on them is the app's dark theme. */
.scheme-dark {
  color-scheme: dark;
${decl(dark, '  ')}
}
`;

fs.mkdirSync(path.dirname(out), { recursive: true });
// (A Windows checkout may hold the file with CRLF line ends: same content.)
const before = fs.existsSync(out) ? fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
if (before !== text) {
  fs.writeFileSync(out, text);
  console.log(`tokens: wrote ${path.relative(process.cwd(), out)} (${light.length} light, ${dark.length} dark)`);
} else {
  console.log('tokens: up to date');
}
